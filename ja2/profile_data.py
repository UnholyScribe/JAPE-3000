"""Data recovered from Jagged Alliance 2, for reading and writing profiles.

Generated by a one-off script; see Documentation/JA2 savegame format.md for how
each table was obtained and, more importantly, how to check it is still right.

KEYSTREAM
    Savegame profile records are enciphered. The scheme is the one JA2 uses
    throughout - JA2EncryptedFileWrite in "Tactical Save.c":

        cipher[i] = plain[i] + cipher[i-1] + key[i]

    Each 716 byte record is its own block, so cipher[-1] is 0 at every record
    start. Because the previous CIPHER byte feeds the next one, changing a
    single plaintext byte shifts every later byte in that record by the same
    amount - which is why an edit shows up as one long uniform run in a diff.

    The game's own Prof.dat uses that formula with the 46 byte ubRotationArray
    from the source. Savegames do NOT - they use a different, 49 entry key
    (see KEY_TABLE below; it repeats, which was only noticed later). It was
    first recovered position by position rather than guessed: Prof.dat decodes to the same MERCPROFILESTRUCT records a save
    holds, so for any untouched profile

        key[i] = (save_delta[i] - prof_plain[i]) mod 256

    Taking the majority across all 170 records cancels out the handful the
    player has actually changed. 629 of the 716 positions were unanimous, and
    the answer was then confirmed two independent ways: it reproduced the nine
    stat offsets that had been measured earlier by editing one field at a time
    in JAPE, and it is byte for byte identical across six different savegames.

    Verified on build 04.12.02, save version 99. A different build may differ,
    so ja2_save checks the version before it will write anything.

    **Offsets 408 and 409 are set by hand, against the majority vote.** The
    vote there was 150 to 20 for 106/241; the answer is the minority, 206/85.
    A majority vote only works where most profiles still match Prof.dat, and
    at this position most of them do not - the game writes something else
    there - so the vote measured the game's habit rather than the key.

    What settles it is that offset 408 is where soldier slot 11's item id
    lives (12 + 11 * 36), and with the vote's value that slot decoded to item
    25771 in every hired merc's record - an id no version of the game has.
    Three records, three different magazines, all give 206/85 independently,
    and each answer is confirmed twice over: it matches the magazine that
    merc's A.I.M. loadout says they set out with, and the round count in the
    slot matches that magazine's capacity (15 for a pistol mag, 30 for an SMG
    mag). Slot 11 is the only one of the nineteen whose id lands on a
    non-unanimous key position, which is why it was the only one that broke.

    This was not only a reading fault. The same offset is used to WRITE that
    slot, so an item put in Pack 1/1 of a hired merc was being stored 100 too
    low. Nothing else reads 408-409: in a profile record they fall inside the
    unmapped gap at 396-415.

    **Offset 230 is set by hand too, to 133.** It is soldier slot 6's item
    count - the left hand - and the vote there was not a majority at all: 32
    with 60 of 170, then 48 with 39, 43 with 37 and 132 with 18. A split like
    that means the byte changes during play, so the vote was never going to
    settle it. What settles it is the item table now read out of ja2.exe,
    which publishes how many of each item fit in one pocket. With the vote's
    value, both mercs carrying something in that hand read a count of 102 -
    102 sticks of TNT, in a slot the game caps at one. Of the five candidate
    values only 133 gives a count within the limit for every record, and it
    gives exactly 1 for both.

    Weaker than the 408 case and worth saying so: the four savegames here are
    one campaign, so that is two independent mercs, not eight. TNT's limit of
    one per pocket is what does the real work - it rules out 132 as well.

    Both hand-set values turned out to be exactly what the 49 entry cycle
    gives, and so are the weak positions that used to be listed here (108,
    404, 574, 575). The cycle replaced the voted table on 2026-10-11.
"""

