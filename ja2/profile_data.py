# -- the checksum, and why this matters -------------------------------------
#
# There IS a checksum: four bytes at 696, with 700..715 zero padding. An
# earlier note in this project called that region "ten int16 stat-gain
# counters, not a checksum" and said nothing in the record is checksummed.
# **That was wrong.** JAPE computes it in ActorChecksum, whose local variables
# are named eax/ebx/edx/edi/esi because it was transcribed from the game's own
# disassembly: it folds the stats at 297, 334, 405, 335, 296, 353, 261, 411,
# 339 and 352 through alternating add and multiply, then loops the 19
# inventory slots.
#
# Our writes do not recompute it, so a save we have edited carries a stale
# value. **That is very probably harmless, on evidence rather than hope:**
# JAPE was watched across nine of its own single-stat edits and it left the
# checksum byte-for-byte unchanged after editing leadership, and again after
# wisdom. JAPE therefore ships stale checksums itself, and JAPE's saves load.
# A field the game hard-validated could not survive that.
#
# Still worth one real load of an edited save before calling it settled.
#
# The algorithm itself is transcribed but not exact. Running JAPE's own
# ActorChecksum bytecode over all 170 profiles reproduces the stored value for
# none of them, but lands on only THREE distinct differences - 1104 for 111
# records, 848 for 58, and one outlier - and 1104 - 848 is exactly 256. That is
# one systematic term being read slightly wrong, not a mangled transcription.
# Anyone finishing this should start there rather than from scratch.
OFF_CHECKSUM = 696
CHECKSUM_LENGTH = 4

