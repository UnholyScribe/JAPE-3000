def name(item_id):
    """A display name for an item id, even one we have never seen."""
    row = ITEMS.get(int(item_id))
    return row[0] if row else ('Item %d' % item_id)


def category(item_id):
    row = ITEMS.get(int(item_id))
    return CATEGORIES[row[1]] if row else ''
